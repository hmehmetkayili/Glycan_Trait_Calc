"""Machine-Readable Trait Metadata Schema and Definitions.

Implements Sections 6, 7, 9, 10, and 11 of the GAREG Glycomic Trait Analyzer Specification:
- 28 Baseline Composition-Derived Glycan Traits (T01 - T28)
- Optional Advanced Compositional Traits (T12b, T08b, T29 - T34)
- 8 Structure-Derived Glycan Traits (S01 - S08)
- Composition and Structure Classification Table (Section 10)
"""

from __future__ import annotations

from dataclasses import dataclass, field, asdict
from typing import Any, Dict, List, Optional
from glycan_trait_calc.core.config import TRAIT_DEFINITION_VERSION


@dataclass
class TraitDefinition:
    """Machine-readable definition of a glycan trait (Section 7)."""
    Trait_ID: str
    Trait_Name: str
    Analytical_Category: str  # "Composition-Derived" | "Structure-Derived"
    Trait_Group: str
    Mathematical_Formula: str
    Plain_Formula: str
    Required_Components: List[str]
    Inclusion_Criteria: str
    Exclusion_Criteria: str
    Numerator_Definition: str
    Denominator_Definition: str
    Unit: str
    Interpretation: str
    Limitations: str
    Calculation_Version: str = TRAIT_DEFINITION_VERSION
    Is_Baseline: bool = True
    Is_Optional: bool = False
    Is_Custom: bool = False
    # Machine-readable evaluation specification for the modular engine
    Engine_Rule: Dict[str, Any] = field(default_factory=dict)

    def to_dict(self) -> Dict[str, Any]:
        return asdict(self)


