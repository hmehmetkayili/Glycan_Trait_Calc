def get_all_trait_definitions(include_optional: bool = True, custom_traits: Optional[List[TraitDefinition]] = None) -> Dict[str, Any]:
    """Return structured dictionary of baseline, optional, custom, and structure-derived trait definitions."""
    comp_traits = list(BASELINE_COMPOSITION_TRAITS)
    if include_optional:
        comp_traits.extend(OPTIONAL_COMPOSITION_TRAITS)
    if custom_traits:
        comp_traits.extend(custom_traits)
    return {
        "version": TRAIT_DEFINITION_VERSION,
        "composition_baseline_count": len(BASELINE_COMPOSITION_TRAITS),
        "composition_optional_count": len(OPTIONAL_COMPOSITION_TRAITS),
        "composition_custom_count": len(custom_traits or []),
        "structure_trait_count": len(STRUCTURE_DERIVED_TRAITS),
        "composition_traits": [t.to_dict() for t in comp_traits],
        "structure_traits": [t.to_dict() for t in STRUCTURE_DERIVED_TRAITS],
        "classification_table": COMPOSITION_STRUCTURE_CLASSIFICATION_TABLE,
    }

